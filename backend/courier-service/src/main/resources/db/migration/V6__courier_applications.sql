-- A courier's application to deliver for SwiftDrop. The courier submits it after
-- registering; an administrator approves or rejects it. Approval activates the
-- identity account and creates the courier profile from these details.
CREATE TABLE courier_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE CHECK (user_id > 0),
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    vehicle_type VARCHAR(30) NOT NULL CHECK (vehicle_type IN ('BICYCLE','MOTORCYCLE','THREE_WHEELER','CAR','VAN','TRUCK')),
    vehicle_number VARCHAR(30) NOT NULL,
    area VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    rejection_reason VARCHAR(500),
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL)
);
CREATE INDEX idx_courier_applications_status ON courier_applications(status, created_at);
