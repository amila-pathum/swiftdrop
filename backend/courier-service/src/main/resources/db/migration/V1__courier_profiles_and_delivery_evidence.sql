CREATE TABLE courier_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE CHECK (user_id > 0),
    name VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
    vehicle_type VARCHAR(30) NOT NULL CHECK (vehicle_type IN ('BICYCLE','MOTORCYCLE','THREE_WHEELER','CAR','VAN','TRUCK')),
    vehicle_number VARCHAR(30) NOT NULL, area VARCHAR(100) NOT NULL,
    availability VARCHAR(20) NOT NULL DEFAULT 'OFFLINE' CHECK (availability IN ('AVAILABLE','BUSY','OFFLINE')),
    active BOOLEAN NOT NULL, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (active OR availability = 'OFFLINE')
);
CREATE INDEX idx_courier_dispatch_list ON courier_profiles(active, availability, area);

CREATE TABLE delivery_checkpoints (
    id UUID PRIMARY KEY, parcel_id UUID NOT NULL,
    courier_id BIGINT NOT NULL REFERENCES courier_profiles(id),
    assignment_id UUID NOT NULL, assignment_version BIGINT NOT NULL,
    attempt_no INT NOT NULL CHECK (attempt_no > 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('PICKED_UP','IN_TRANSIT','OUT_FOR_DELIVERY','DELIVERED','FAILED')),
    sync_status VARCHAR(20) NOT NULL CHECK (sync_status IN ('PENDING','CONFIRMED','REJECTED','UNKNOWN')),
    planned_address_snapshot VARCHAR(1000), location_description VARCHAR(500),
    latitude NUMERIC(9,6), longitude NUMERIC(9,6), accuracy_meters NUMERIC(10,2),
    captured_at TIMESTAMPTZ, recorded_at TIMESTAMPTZ NOT NULL, note VARCHAR(1000),
    fingerprint VARCHAR(64) NOT NULL, lease_until TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0,
    CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CHECK (latitude BETWEEN -90 AND 90), CHECK (longitude BETWEEN -180 AND 180),
    CHECK (accuracy_meters >= 0)
);
CREATE INDEX idx_checkpoint_tracking ON delivery_checkpoints(parcel_id, courier_id, recorded_at);

CREATE TABLE delivery_proofs (
    id UUID PRIMARY KEY, parcel_id UUID NOT NULL,
    courier_id BIGINT NOT NULL REFERENCES courier_profiles(id),
    checkpoint_id UUID NOT NULL UNIQUE REFERENCES delivery_checkpoints(id),
    attempt_no INT NOT NULL CHECK (attempt_no > 0),
    outcome VARCHAR(30) NOT NULL CHECK (outcome IN ('DELIVERED','FAILED')),
    recipient_name VARCHAR(150), photo_key VARCHAR(50), failure_reason VARCHAR(40), note VARCHAR(1000),
    collection_address_snapshot VARCHAR(1000), delivery_address_snapshot VARCHAR(1000),
    recorded_at TIMESTAMPTZ NOT NULL,
    UNIQUE (parcel_id, attempt_no),
    CHECK (outcome <> 'DELIVERED' OR NULLIF(TRIM(recipient_name), '') IS NOT NULL OR photo_key IS NOT NULL),
    CHECK (outcome <> 'FAILED' OR failure_reason IS NOT NULL)
);
