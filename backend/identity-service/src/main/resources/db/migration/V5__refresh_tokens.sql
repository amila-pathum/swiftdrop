-- Phase 5: refresh tokens.

-- Single-use refresh tokens, rotated on every refresh. Only a SHA-256 hash of
-- each token is stored. Tokens issued from one sign-in share a family_id so a
-- reused (stolen) token can revoke the whole family. token_version is the
-- user's token_version at issue: once the user's version moves on (logout,
-- password change or reset, role or status change) the token is refused.
CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    token_hash varchar(64) NOT NULL,
    user_id bigint NOT NULL,
    family_id varchar(36) NOT NULL,
    token_version integer NOT NULL,
    persistent boolean NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
