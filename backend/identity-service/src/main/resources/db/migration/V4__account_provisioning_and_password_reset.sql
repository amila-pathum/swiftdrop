-- Phase 4: logout/session invalidation and password reset.

-- Incremented to invalidate every access token already issued to a user
-- (logout, password reset). Tokens carry the version they were issued with.
ALTER TABLE users ADD COLUMN token_version integer NOT NULL DEFAULT 0;

-- Single-use password reset tokens. Only a SHA-256 hash of each token is
-- stored; the raw token is shown once to whoever requested it.
CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    token_hash varchar(64) NOT NULL,
    user_id bigint NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT password_reset_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT uk_password_reset_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_password_reset_tokens_user_id ON password_reset_tokens (user_id);
CREATE INDEX idx_password_reset_tokens_expires_at ON password_reset_tokens (expires_at);
