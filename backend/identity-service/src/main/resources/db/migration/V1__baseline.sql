-- Baseline: the schema exactly as Hibernate (ddl-auto=update) created it before
-- Flyway was introduced. Existing databases are baselined at version 1 and skip
-- this script; new databases run it to reach the same starting point.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    email varchar(255) NOT NULL,
    name varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(30) NOT NULL,
    status varchar(30) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT users_role_check
        CHECK (role IN ('CUSTOMER', 'MERCHANT', 'COURIER', 'DISPATCHER', 'ADMIN')),
    CONSTRAINT users_status_check
        CHECK (status IN ('ACTIVE', 'PENDING_APPROVAL', 'SUSPENDED', 'DISABLED'))
);
