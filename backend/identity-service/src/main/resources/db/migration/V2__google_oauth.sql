-- Google OAuth sign-in.

-- Accounts created through Google have no SwiftDrop password.
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- External identities linked to a SwiftDrop user, keyed by the provider's
-- stable subject identifier (Google "sub"), never by email.
CREATE TABLE user_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    provider varchar(30) NOT NULL,
    provider_subject varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT user_identities_pkey PRIMARY KEY (id),
    CONSTRAINT fk_user_identities_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_user_identities_provider_subject UNIQUE (provider, provider_subject),
    -- One identity per provider per user.
    CONSTRAINT uk_user_identities_user_provider UNIQUE (user_id, provider),
    CONSTRAINT user_identities_provider_check CHECK (provider IN ('GOOGLE'))
);

-- Single-use codes handed to the frontend after a successful OAuth login and
-- exchanged for a SwiftDrop JWT. Only a SHA-256 hash of each code is stored.
CREATE TABLE oauth_login_codes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    code_hash varchar(64) NOT NULL,
    user_id bigint NOT NULL,
    client_challenge varchar(64) NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT oauth_login_codes_pkey PRIMARY KEY (id),
    CONSTRAINT uk_oauth_login_codes_code_hash UNIQUE (code_hash),
    CONSTRAINT fk_oauth_login_codes_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_oauth_login_codes_expires_at ON oauth_login_codes (expires_at);
