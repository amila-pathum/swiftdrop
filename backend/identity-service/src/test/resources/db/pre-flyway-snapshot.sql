-- Structure of the development identity_db before Flyway, taken from
-- `pg_dump --schema-only` (no data), plus two sample rows. Used to test that an
-- existing database is baselined and migrated without losing data.
--
-- The CHECK constraints are written as Hibernate created them (IN (...)).
-- Replaying pg_dump's own rendering makes PostgreSQL store a differently
-- formatted (equivalent) expression, which would no longer match the real
-- database byte for byte.

CREATE TABLE public.users (
    id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    email character varying(255) NOT NULL,
    name character varying(100) NOT NULL,
    password_hash character varying(255) NOT NULL,
    role character varying(30) NOT NULL,
    status character varying(30) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT users_role_check
        CHECK (role IN ('CUSTOMER', 'MERCHANT', 'COURIER', 'DISPATCHER', 'ADMIN')),
    CONSTRAINT users_status_check
        CHECK (status IN ('ACTIVE', 'PENDING_APPROVAL', 'SUSPENDED', 'DISABLED'))
);

ALTER TABLE public.users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.users_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.users
    ADD CONSTRAINT uk_users_email UNIQUE (email);

ALTER TABLE ONLY public.users
    ADD CONSTRAINT users_pkey PRIMARY KEY (id);

